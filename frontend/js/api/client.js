// 📄 client.js — 우리 서버(MealMeter-BE)에 "요청을 보내는 창구" 딱 하나          담당: 조현우
// ============================================================================
//
// 🍽️ 비유로 이해하기
//   식당에서 손님(화면)이 주방(서버)에 직접 들어가지 않고 "점원" 한 명에게만 주문하듯이,
//   우리 화면 코드는 서버에 직접 말을 걸지 않고 이 파일의 request() 함수에게만 부탁한다.
//   점원(request)은 주문을 전달하고, 음식(데이터)을 받아 오고, 문제가 생기면 "죄송합니다, ~때문에 안 돼요"라고
//   손님이 알아들을 수 있는 한국어 한 줄로 알려 준다.
//
// 📦 이 파일이 내보내는 것
//   request('/api/ranking')                    → 서버에서 순위 데이터를 "가져온다"(GET)
//   request('/api/reviews', 'POST', 평가객체)  → 서버에 새 평가를 "보낸다"(POST)
//
// 🔄 request() 한 번이 하는 일 (순서대로)
//   1) fetch에 넘길 설정(주문서)을 만든다
//   2) 서버에 요청을 보낸다        → 아예 연결이 안 되면 "인터넷 연결을 확인해 주세요" 오류
//   3) 서버의 답장(JSON)을 읽는다  → 읽을 수 없는 답장이면 broken = true 로 표시
//   4) 서버가 "실패"라고 답했으면  → 서버가 적어 준 이유(message)로 오류
//   5) 성공인데 답장이 깨졌으면    → "서버 응답을 읽지 못했어요" 오류
//   6) 다 괜찮으면 받은 데이터를 돌려준다
//
// 📌 약속 (명세서 5장)
//   서버는 실패하면 { "message": "한 줄 오류 메시지" } 모양으로 답한다.
//   그래서 화면은 이 message를 그대로 사용자에게 보여 주면 된다.
//
// 💡 용어
//   - 요청(request) / 응답(response): 브라우저가 서버에 보내는 편지 / 서버가 돌려주는 답장
//   - JSON: 서버와 주고받는 데이터 글자 형식. 예) {"name":"닭갈비","rating":5}
//   - 상태 코드: 답장에 붙은 숫자. 200번대 = 성공, 400번대 = 요청이 잘못됨, 500번대 = 서버 문제
// ============================================================================

// 서버가 이유를 안 알려 줬을 때 대신 보여 줄 기본 오류 문구
// [문법] const: 다시 대입할 수 없는 변수. 대문자_이름은 "바뀌지 않는 설정값"이라는 표시로 흔히 쓴다
const DEFAULT_ERROR = '요청을 처리하지 못했어요. 잠시 후 다시 시도해 주세요.';

// ----------------------------------------------------------------------------
// request(path, method, data) — 서버에 요청을 보내고 답장을 객체로 돌려준다
//
//   받는 값
//     path   : 서버 주소 중 뒷부분. 예) '/api/ranking', '/api/menus/3/reviews'
//     method : 요청 종류. 'POST'(새로 만들기), 'PATCH'(고치기). 안 넘기면 기본 GET(가져오기)
//     data   : 서버에 보낼 객체. 예) { menuId: 3, rating: 5, ... }. 보낼 게 없으면 안 넘긴다
//
//   돌려주는 값
//     성공 → 서버가 보낸 데이터(객체나 배열)
//     실패 → 값을 돌려주는 대신 Error를 "던진다"(throw). 부른 쪽의 catch에서 err.message로 받는다
//
//   쓰는 예
//     const ranking = await request('/api/ranking');
//     const saved   = await request('/api/reviews', 'POST', { menuId: 3, rating: 5 });
// ----------------------------------------------------------------------------
// [문법] export: 다른 파일에서 import { request } 로 가져다 쓸 수 있게 내보낸다
// [문법] async function: "기다려야 하는 일"(서버 응답 등)이 들어 있는 함수. 안에서 await를 쓸 수 있다
//        async 함수를 부르면 결과 대신 Promise(= "나중에 결과를 줄게"라는 약속표)가 먼저 돌아온다
export async function request(path, method, data) {
  // ── 1단계: 주문서(fetch 설정) 만들기 ─────────────────────────────
  // headers는 편지 봉투에 적는 메모 같은 것.
  // 'Content-Type': 'application/json' = "제가 보내는 내용은 JSON 형식이에요"라고 서버에 알려 준다
  const settings = {
    headers: { 'Content-Type': 'application/json' },
  };
  // method를 넘겼을 때만(POST, PATCH) 주문서에 적는다. 안 적으면 fetch가 알아서 GET으로 보낸다
  // [문법] 인자를 안 넘기면 그 값은 undefined. if (undefined)는 거짓이라 안쪽이 실행되지 않는다
  if (method) {
    settings.method = method;
  }
  // 보낼 데이터가 있으면 body(편지 본문)에 담는다
  if (data) {
    // 객체는 그대로 보낼 수 없어서 JSON 글자로 바꿔야 한다
    // [문법] JSON.stringify({ rating: 5 }) → '{"rating":5}' (객체 → 글자)
    settings.body = JSON.stringify(data);
  }

  // ── 2단계: 서버에 보내기 ─────────────────────────────────────────
  // response(답장)는 try 안에서 받지만 try 밖에서도 써야 해서, 여기서 미리 빈 상자를 만들어 둔다
  // [문법] let: 나중에 값을 넣거나 바꿀 수 있는 변수. 지금은 값이 없으니 undefined
  let response;
  // [문법] try { A } catch (err) { B }: A를 해 보다가 오류가 나면 프로그램이 멈추지 않고 B로 넘어간다
  try {
    // [문법] fetch(주소, 설정): 브라우저에 들어 있는 "서버에 요청 보내기" 함수
    // [문법] await: 답장이 올 때까지 이 줄에서 기다린다. 그동안 화면은 멈추지 않는다
    response = await fetch(path, settings);
  } catch (err) {
    // fetch 자체가 실패했다 = 답장을 아예 못 받았다 = 인터넷이 끊겼거나 서버가 꺼져 있다
    // [문법] throw new Error('글자'): 오류를 "던진다". 이 함수는 여기서 끝나고, 부른 쪽 catch로 날아간다
    throw new Error('서버에 연결하지 못했어요. 인터넷 연결을 확인해 주세요.');
  }

  // ── 3단계: 답장 내용 읽기 ────────────────────────────────────────
  // body  : 답장 내용을 객체로 바꾼 것 (아직 모르니 null로 시작)
  // broken: 답장이 JSON이 아니라서 못 읽었는지 표시하는 깃발 (처음엔 false = 괜찮음)
  let body = null;
  let broken = false;
  try {
    // [문법] response.json(): 답장 글자를 객체로 바꾼다. 이것도 시간이 걸려서 await로 기다린다
    body = await response.json();
  } catch (err) {
    // 답장이 깨졌거나 JSON이 아니면 여기로 온다. 바로 오류를 던지지 않고 깃발만 세워 둔다
    // (실패 응답이면 아래 4단계에서 기본 문구로 알려 주려고)
    broken = true;
  }

  // ── 4단계: 서버가 "실패"라고 답했는지 확인 ────────────────────────
  // [문법] response.ok: 상태 코드가 200~299(성공)면 true, 아니면 false
  // [문법] !response.ok: ! 는 참/거짓을 뒤집는다 → "성공이 아니면"
  if (!response.ok) {
    // 답장을 제대로 읽었고, 그 안에 message(이유)가 있으면 그 이유를 그대로 보여 준다
    // 예) 서버: { "message": "욕설이나 비방 표현은 등록할 수 없어요." } → 사용자도 이 문장을 본다
    // [문법] A && B && C: 셋 다 참이어야 참
    if (!broken && body && body.message) {
      throw new Error(body.message);
    }
    // 이유를 알 수 없으면 기본 문구로 알려 준다
    throw new Error(DEFAULT_ERROR);
  }

  // ── 5단계: 성공했는데 답장이 깨진 경우 ───────────────────────────
  // 그냥 넘어가면 화면이 데이터를 못 받아 "불러오는 중…"에서 영원히 멈출 수 있어서 오류로 알린다
  if (broken) {
    throw new Error('서버 응답을 읽지 못했어요. 잠시 후 다시 시도해 주세요.');
  }

  // ── 6단계: 모두 통과! 받은 데이터를 돌려준다 ──────────────────────
  return body;
}
