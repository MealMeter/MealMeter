// 🤔 왜 이 파일이 따로 있을까?
//   "간은 짜다/적당/싱겁다 중에 고른다", "의견은 100자까지" 같은 규칙을 여러 파일에 따로 적으면
//   하나만 바뀌어도 모든 파일을 찾아다니며 고쳐야 하고, 하나라도 빠뜨리면 버그가 난다.
//   그래서 규칙은 여기 한 곳에만 적고, 다른 파일은 여기서 가져다 쓴다. (명세서 3장 기능 2, 4장)
//
// ⚠️ 서버(MealMeter-BE의 app/rules.py)에도 같은 규칙이 있다.
//    여기를 바꾸면 서버도 꼭 같이 바꿔야 한다! (안 그러면 서버가 "그런 값은 없어요"라고 거절한다)
//
// 💡 key와 label의 차이
//   key   : 서버로 보낼 때 쓰는 영어 이름표. 예) 'saltiness'
//   label : 화면에 보여 주는 한국어 이름.    예) '간'
//
// 📦 이 파일이 내보내는 것
//   TAG_FIELDS          간·양·온도·식감 태그 목록
//   HYGIENE_FIELD       위생 태그 (따로 다룬다)
//   HYGIENE_PROBLEM     위생 "문제 있음" 값
//   COMMENT_MAX_LENGTH  의견 최대 글자 수
//   MEAL_TYPES          식사 번호 → 이름 (1 조식, 2 중식, 3 석식)
//   DEFAULT_MEAL_CODE   기본 식사(중식)
//   RATING_LABELS       별점마다 붙는 말 (4점 → '좋아요')
// ============================================================================

// 태그 항목 4개. 평가할 때 각 항목에서 하나를 고르거나, 안 골라도 된다(안 고르면 null로 보낸다)
// [문법] export const: 바꾸지 않는 값(상수)을 다른 파일에서 import { TAG_FIELDS } 로 쓸 수 있게 내보낸다
// [문법] [ { ... }, { ... } ]: 객체 여러 개가 들어 있는 배열. 객체 하나 = 태그 항목 하나
//        TAG_FIELDS[0].label → '간',  TAG_FIELDS[0].options[1] → '적당'
export const TAG_FIELDS = [
  // key: 서버 필드 이름 / label: 화면 이름 / options: 고를 수 있는 값들(서버에도 이 글자 그대로 보낸다)
  { key: 'saltiness', label: '간', options: ['짜다', '적당', '싱겁다'] },
  { key: 'portion', label: '양', options: ['많다', '적당', '적다'] },
  { key: 'temperature', label: '온도', options: ['뜨겁다', '적당', '차갑다'] },
  { key: 'texture', label: '식감', options: ['무름', '적당', '딱딱'] },
];

// 위생 태그. "음식에 이물질이 나왔다" 같은 사고 신고에 가까워서 다른 태그와 따로 다룬다.
//   - 화면: 빨간 경고 모양으로 따로 보여 준다
//   - 목록: "문제 있음"이면 맨 앞에 경고 배지로 표시한다
// [문법] 객체 하나짜리 상수. HYGIENE_FIELD.key → 'hygiene' 처럼 점(.)으로 꺼내 쓴다
export const HYGIENE_FIELD = { key: 'hygiene', label: '위생', options: ['문제 있음', '없음'] };
// "문제 있음" 글자를 여러 곳에서 비교하니까 상수로 만들어 둔다 (오타 방지)
export const HYGIENE_PROBLEM = '문제 있음';

// 자유 의견 최대 글자 수 (명세서 제안값. 팀 회의에서 바뀌면 여기만 고친다)
// 의견 입력창의 최대 길이와 "12 / 100자" 글자 수 표시에 같이 쓴다
export const COMMENT_MAX_LENGTH = 100;

// 식사 번호 → 이름. 번호는 나이스 급식 API의 식사코드와 같다
// [문법] { 1: '조식', ... }: 숫자처럼 보이는 이름표를 가진 객체. MEAL_TYPES[2] → '중식'
// [문법] (이름표는 사실 글자 '1', '2'로 저장되지만, MEAL_TYPES[2]처럼 숫자로 꺼내도 똑같이 된다)
//        없는 번호를 꺼내면 undefined → "올바른 식사 번호인지" 검사할 때도 쓴다. 예) MEAL_TYPES[7] → undefined
export const MEAL_TYPES = { 1: '조식', 2: '중식', 3: '석식' };
// 식사를 따로 정하지 않았을 때 쓰는 기본값 (2 = 중식)
export const DEFAULT_MEAL_CODE = 2;

// 별점마다 붙는 말. RATING_LABELS[4] → '좋아요'
// (화면에만 쓰고 서버로는 보내지 않아서 서버의 app/rules.py에는 없다)
// [문법] 배열은 0번 칸부터 시작한다. 별점은 1~5점이라 0번 칸은 빈 글자('')로 채워 자리만 맞췄다.
//        그래서 RATING_LABELS[별점]으로 바로 꺼낼 수 있다 (빼기 1을 안 해도 됨)
export const RATING_LABELS = ['', '별로예요', '아쉬워요', '보통이에요', '좋아요', '최고예요'];
